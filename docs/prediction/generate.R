# With gltbnn installed, run Rscript generate.R in this directory.
# This regenerates the numerical values the browser reads from data.js.
library(gltbnn)
set.seed(418)
x <- seq(-2, 2, length.out = 36L)
y <- 5 + 1.7 * sin(1.5 * x) + 0.3 * x + rnorm(length(x), sd = 0.45)
training <- data.frame(x = x)
grid <- data.frame(x = seq(-2, 2, length.out = 81L))
numbers <- function(z) paste0("[", paste(sprintf("%.7f", z), collapse = ","), "]")
out <- c("// Generated by generate.R using gltbnn.",
         "const regressionExample = {",
         paste0("  x: ", numbers(x), ","),
         paste0("  y: ", numbers(y), ","),
         paste0("  grid: ", numbers(grid$x), ","),
         "  fits: {")
for (prior in c("G", "GL", "GLT")) {
  fit <- gltbnn_fit(training, y, hidden = 8L, prior = prior, seed = 17L)
  units <- gltbnn_shrinkage(fit)
  # Reusing the seed matches the weight draws in both sets of predictions.
  mean_draws <- predict(fit, grid, type = "mean_draws", draws = 2048L, seed = 23L)
  new_draws <- predict(fit, grid, type = "response_draws", draws = 2048L, seed = 23L)
  bounds <- function(draws) {
    t(apply(draws, 1L, quantile, probs = c(0.05, 0.95), names = FALSE))
  }
  latent <- bounds(mean_draws)
  response <- bounds(new_draws)
  tail_shape <- units$geometric_tail_shape[1]
  out <- c(out, paste0("    ", prior, ": {"),
           paste0("      geometric_prior_sd: ", numbers(units$geometric_prior_sd), ","),
           sprintf("      geometric_layer_scale: %.7f,", units$geometric_layer_scale[1]),
           paste0("      geometric_tail_shape: ", if (is.na(tail_shape)) "null" else sprintf("%.7f", tail_shape), ","),
           paste0("      mean: ", numbers(rowMeans(mean_draws)), ","),
           paste0("      meanLow: ", numbers(latent[, 1]), ","),
           paste0("      meanHigh: ", numbers(latent[, 2]), ","),
           paste0("      responseLow: ", numbers(response[, 1]), ","),
           paste0("      responseHigh: ", numbers(response[, 2])),
           "    },")
}
serialized <- paste(c(out, "  }", "};", ""), collapse = "\n")
writeBin(charToRaw(serialized), "data.js")
