"""Typeset the comparison page's equations as native MathML for offline use."""
from html import escape
import json
from pathlib import Path

from latex2mathml.converter import convert


equations = {
    "noPenalty": r"C(w)=0",
    "l1Penalty": r"C(w)=\eta_{\mathrm{reg}}\lvert w\rvert",
    "priorCost": r"C(m,s)=\frac{\omega}{2}(m^2+s^2)",
    "precision": r"\omega=\mathbb{E}_q(\sigma^{-2})\,\mathbb{E}_q(\lambda^{-2})",
    "residual": r"e_i=y_i-f_{\mathcal W}(\mathbf{x}_i)",
    "maskedResidual": r"e_i(M_i)=y_i-f_{\mathcal W,M_i}(\mathbf{x}_i)",
    "leastSquares": r"\mathcal J=\frac{1}{2n}\sum_{i=1}^n e_i^2",
    "penalizedLoss": r"\mathcal J=\frac{1}{2n}\sum_{i=1}^n e_i^2+\eta_{\mathrm{reg}}\sum_a\lvert w_a\rvert",
    "dropoutLoss": r"\mathcal J=\frac{1}{2n}\sum_{i=1}^n\mathbb{E}_{M_i}\!\left[e_i(M_i)^2\right]",
    "elbo": r"\mathcal L(q)=\mathbb{E}_q\!\left[\log\frac{p(\mathcal D\mid\Theta)\,\pi(\Theta)}{q(\Theta)}\right]",
    "relu": r"h=\max\{0,z\}",
    "dropout": r"h_{\mathrm{pass}}=\frac{M}{0.8}\,h",
    "draw": r"w=m+s\epsilon,\qquad \epsilon\sim\mathcal{N}(0,1)",
    "fnnVolume": r"\widehat Y(\mathbf{x}_*)=\bar{y}+s_y f_{\widehat{\mathcal{W}}}(\mathbf{x}_*)",
    "bnnVolume": r"\widehat Y_S(\mathbf{x}_*)=\bar{y}+\frac{s_y}{S}\sum_{r=1}^S f_{\mathcal{W}^{(r)}}(\mathbf{x}_*)",
}


def typeset(tex):
    math = convert(tex, display="block")
    return math.replace("<math ", f'<math alttext="{escape(tex, quote=True)}" ', 1)


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[2] / "docs/computation/regularization-math.js"
    rendered = {key: typeset(tex) for key, tex in equations.items()}
    target.write_text(
        "// Generated by tools/site/regularization_math.py.\n"
        + "const regularizationMath = "
        + json.dumps(rendered, ensure_ascii=False, indent=2)
        + ";\n", encoding="utf8",
    )
